"""The socket layer's IDNA 2003 encoding, as every interpreter computes it.

urllib.request and http.client hand a non-ASCII host to the socket layer, which
encodes it with the stdlib ``idna`` codec. CPython fixed that codec's
``stringprep`` late (3.10.22, 3.12.15, 3.14.9): before the fix, a code point RFC
3454's table B.3 does not map was lowercased by the interpreter's own Unicode, so
3.10.20, 3.11.15, 3.12.2, 3.12.13 and 3.14.5 each encode some names their own way.
Every one of those names is a name a real client resolves, so the core reads all of
them (``_idna.idna2003``), from fixed data, the same list on every interpreter.

The data is generated by ``scripts/gen_value_origin_data.py --nameprep`` from files
vendored in ``scripts/value_origin_sources/``; each one's sha256 is in SOURCES.json.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
from pathlib import Path

import pytest

from xaidr.value_origin import _nameprep_data as N
from xaidr.value_origin._idna import idna2003

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "scripts" / "value_origin_sources"


def test_the_vendored_sources_are_their_recorded_bytes():
    manifest = json.loads((SOURCES / "SOURCES.json").read_text(encoding="utf-8"))
    assert {e["path"] for e in manifest["files"]} == {
        "rfc3454.txt", "UnicodeData-16.0.0.txt", "DerivedAge-16.0.0.txt",
        "SpecialCasing-16.0.0.txt", "LICENSES/Unicode-license.txt"}
    for entry in manifest["files"]:
        got = hashlib.sha256((SOURCES / entry["path"]).read_bytes()).hexdigest()
        assert got == entry["sha256"], (
            f"{entry['path']} is not the file SOURCES.json records ({entry['url']}, "
            f"{entry['version']}): sha256 {got}, recorded {entry['sha256']}. The core's "
            "IDNA 2003 tables would no longer be the published ones.")
        if "licence_file" in entry:
            assert (SOURCES / entry["licence_file"]).is_file(), entry


def test_the_tables_are_what_the_vendored_sources_generate():
    """A hand edit of ``_nameprep_data.py``, or a source swapped without
    regenerating, is red: the module must be byte for byte what the committed
    generator writes from the vendored files."""
    spec = importlib.util.spec_from_file_location(
        "gen_value_origin_data", ROOT / "scripts" / "gen_value_origin_data.py")
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    written = (ROOT / "xaidr" / "value_origin" / "_nameprep_data.py").read_text(encoding="utf-8")
    assert gen.gen_nameprep(SOURCES) == written, (
        "_nameprep_data.py is not what scripts/gen_value_origin_data.py --nameprep "
        "writes from scripts/value_origin_sources/")
    assert len(N.B1) == 27 and len(N.B3) == 838                  # the RFC's row counts


# Each host's readings are every name a real interpreter's codec gives it, measured
# 2026-10-24 on 3.10.20, 3.10.22, 3.11.15, 3.12.2, 3.12.13, 3.12.15, 3.14.5 and
# 3.14.9 (``host.encode("idna")``), not the core's output.
@pytest.mark.parametrize("host,names", [
    ("straße.example", ["strasse.example"]),
    ("Éxample.test", ["xn--xample-9ua.test"]),
    # Unicode 1.1, lowercased by every unfixed interpreter, kept by every fixed one
    ("Ⴜ.example", ["xn--0nd.example", "xn--klj.example"]),
    ("ⴜ.example", ["xn--klj.example"]),
    # Unicode 14.0: lowercased by an unfixed 3.11, 3.12 or 3.14, kept by 3.10
    ("aⰯ.example", ["xn--a-2ls.example", "xn--a-cjs.example"]),
    # Unicode 16.0: lowercased by an unfixed 3.14 alone
    ("aꟌ.example", ["xn--a-m63e.example", "xn--a-o63e.example"]),
    ("\U00010d50x.example", ["xn--x-go6i.example", "xn--x-mm6i.example"]),
    # all three: fixed, unfixed 3.10, unfixed 3.11 and 3.12, unfixed 3.14
    ("ႼⰯꟌ.example", ["xn--0nd861lpp1g.example", "xn--5fjzwq351a.example",
                                    "xn--5fjzwt351a.example", "xn--sejx4ar850a.example"]),
])
def test_every_interpreters_encoding_is_read_on_every_interpreter(host, names):
    assert sorted(idna2003(host)) == names, (
        f"{host!r}: the core reads {sorted(idna2003(host))}, while the interpreters' "
        f"codecs resolve {names}; a name a client resolves and the core does not read "
        "is a destination value origin never looks at")


def test_this_interpreters_codec_reading_is_among_them():
    """Wherever two interpreters can encode a host differently (a code point B.3
    maps or drops, or one some Unicode lowercases), this interpreter's own codec
    reading is one the core reads. On a fixed interpreter that is RFC 3454's B.3;
    on an unfixed one, its own Unicode's lowercase."""
    missing, n = [], 0
    for cp in sorted(set(N.LOWER) | set(N.B3) | N.B1):
        host = "a" + chr(cp) + ".example"
        try:
            sent = host.encode("idna").decode("ascii")
        except UnicodeError:
            continue
        n += 1
        if sent not in idna2003(host):
            missing.append((hex(cp), sent, idna2003(host)))
    assert n >= 1_500, n
    assert not missing, (
        f"{len(missing)} hosts this interpreter's socket layer resolves under a name "
        f"the core does not read, e.g. {missing[:5]}")
